export const DICTIONARIES: Record<Language, Record<string, string>> = { fr, en };

/** Langue du navigateur, si supportée. */
export function detectLanguage(): Language {
  if (typeof navigator === "undefined") return "fr";
  const lang = (navigator.language || "").toLowerCase();
  return lang.startsWith("fr") ? "fr" : "en";
}

/** Traduction : la clé si absente (le FR étant la référence, la clé
 * FR est utilisée directement comme fallback anglais manquant). */
export function translate(lang: Language, key: string): string {
  return DICTIONARIES[lang][key] ?? fr[key] ?? key;
}
